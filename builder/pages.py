"""Generating the gallery pages.

Every page here is a pure function of the metadata files: same text in, same bytes out.
Nothing is read off an image, nothing is stamped with a date, and the only ordering is
the one the metadata gives. That is what makes `check`'s regenerate-and-compare a real
check rather than a coin toss.
"""

import re
from pathlib import Path

from . import figures, heads, icons, links, packs, records
from . import palettes as palettes_module
from . import sections as sections_module
from .escape import attribute, text
from .galleries import Gallery
