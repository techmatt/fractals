#: What a block's lines are joined with. Named because these pages are assembled inside
#: f-strings, and a bare escape inside one is a character nobody can see in a diff.
NEWLINE = "\n"

GENERATED_NOTICE = (
    "<!-- Generated by builder/. Do not edit by hand — run `python -m builder build`. -->"
)

SITE_TITLE = "Making Fractal Wallpapers"

#: The pipeline's code — the project this article is about. Named wherever the article
#: talks about how the pictures were made, and in the footer.
CODE_REPO = "https://github.com/techmatt/fractal-wallpapers"

#: This site's own code *(figure_split_overview_ckpt140, 2026-09-22)*. The bar's `GitHub`
#: used to point next door, which is the one link on the page a reader cannot guess wrong:
#: a bar link named after the site is the site, and somebody who wanted to see how a page
#: they were reading is built landed in a renderer instead. The pipeline is still one click
#: away — the contents rail carries it, the footer carries it, and the article names it
#: wherever it talks about the code that drew the pictures.
SITE_REPO = "https://github.com/techmatt/fractals"

AUTHOR_SITE = "https://techmatt.github.io/"

#: Where the committed tree is served. The site itself never spells it — every href is
#: relative — and it exists for what leaves the site: a review doc's links resolve here.
SITE_URL = "https://techmatt.github.io/fractals/"

FOOTER = f"""<footer>
  <p><a href="{AUTHOR_SITE}">Matt Fisher</a>
  · <a href="{CODE_REPO}">fractal-wallpapers</a> · MIT</p>
</footer>"""


def index_path() -> str:
    return "index.html"


def gallery_page_path(gallery: Gallery):
    return GALLERIES_DIR / f"{gallery.slug}.html"


def topbar(page: Path) -> str:
    """The site bar every page carries: back to the front page, to the wallpaper packs, the
    tools and data, and the deep zoom videos, out to this site's own source and to the
    author's homepage — this site is one project of several living under it.

    The one spelling of it *(preclose_website_ckpt156)*. A generated page gets it from its
    shell and a hand-written page gets it from `build`, which replaces the `<nav>` the page
    carries; `check`'s `bar` holds every page to it. The bar is the same line everywhere,
    and only its depth differs, which `relative_href` spells from the page.
    """

    def href(target: Path) -> str:
        return attribute(relative_href(page, target))

    return "\n".join(
        [
            '<nav class="topbar">',
            '  <div class="topbar-inner">',
            f'    <a class="topbar-site" href="{href(SITE_ROOT / index_path())}">'
            f"{text(SITE_TITLE)}</a>",
            '    <span class="topbar-links"><a href="'
            f'{href(GALLERIES_DIR / index_path())}">{text(sections_module.PACKS_NAME)}</a>'
            f'<a href="{href(sections_module.TOOLS)}">{text(sections_module.TOOLS_NAME)}</a>'
            f'<a href="{href(sections_module.VIDEOS)}">{text(sections_module.VIDEOS_NAME)}</a>'
            f'<a href="{SITE_REPO}">GitHub</a><a href="{AUTHOR_SITE}">Matt Fisher</a></span>',
            "  </div>",
            "</nav>",
        ]
    )


#: The bar a page carries, from its opening tag to its closing one. What `build` replaces
#: and what `check` reads; no page nests a `<nav>` inside it.
_BAR = re.compile(r'<nav class="topbar">.*?</nav>', re.S)


def with_topbar(page: Path, page_html: str) -> str:
    """The page with its site bar replaced by today's."""
    if _BAR.search(page_html) is None:
        raise records.RecordError(
            f"{page.relative_to(SITE_ROOT).as_posix()}: no site bar — the page skeleton "
            'carries `<nav class="topbar">` right after `<body>`'
        )
    return _BAR.sub(lambda _: topbar(page), page_html, count=1)


def topbar_problems(hand_written: list[Path]) -> list[str]:
    """`check`'s `bar`: every hand-written page carries today's bar, and so does any other
    served page that carries one at all.

    The generated pages are `pages`'s to hold, whole, so a bar there that is not today's is
    already a failure; they are read again here only so that this check means every page.
    The explorer, the atlas redirect and the `go/` redirects carry none, and are not asked to.
    """
    found = []
    must = set(hand_written)
    for path in site_pages():
        with path.open(encoding="utf-8", newline="") as handle:
            html = handle.read()
        if path not in must and _BAR.search(html) is None:
            continue
        try:
            if with_topbar(path, html) != html:
                shown = path.relative_to(SITE_ROOT).as_posix()
                found.append(f"{shown}: its site bar is not today's — run `build`")
        except records.RecordError as error:
            found.append(str(error))
    return found


def _shell(
    *,
    page: Path,
    title: str,
    css: str,
    bar: str,
    rail: str,
    header: str,
    blocks: list[str],
    base: str | None = None,
) -> str:
    """The shape every page has: the site bar, the contents rail, the column beside it.

    A gallery is not an article section, so no entry in the rail is the current one
    here — on these pages the rail is the way back into the article.
    """
    body = "\n\n".join(blocks)
    html = (
        "\n".join(
            [
                "<!doctype html>",
                '<html lang="en">',
                "<head>",
                GENERATED_NOTICE,
                '<meta charset="utf-8">',
                *([f'<base href="{attribute(base)}">'] if base else []),
                '<meta name="viewport" content="width=device-width, initial-scale=1">',
                # **The site's icon, declared on every page** *(favicon_wire_ckpt145)*. A
                # browser asks every origin for `/favicon.ico` unbidden, and under a
                # project-Pages subpath this site cannot answer at the origin root, so a page
                # that declares nothing logs a 404. `builder.icons` owns the lines and spells
                # them from the page; the hand-written pages get the same lines from `build`.
                icons.head(page),
                f"<title>{text(title)}</title>",
                f'<link rel="stylesheet" href="{css}">',
                "</head>",
                "<body>",
                bar,
                "",
                '<div class="page">',
                rail,
                "",
                '<div class="page-body">',
                header,
                "",
                "<main>",
                body,
                "</main>",
                "",
                FOOTER,
                "</div>",
                "</div>",
                "</body>",
                "</html>",
            ]
        )
        + "\n"
    )
    # The description and preview tags are read off the page they describe, so they go in
    # last, once there is a page to read them off.
    return heads.with_head(page, html)


def _masthead(kicker: str | None, heading: str) -> str:
    """The page's own title block: a kicker where one earns its place, and the title.

    Nothing else. Site branding lives in the bar above it, so a page whose kicker would
    only have repeated the site title carries no kicker at all — and no page here carries
    a standfirst, because the ruling in `writing-guidance.md` cut the device site-wide.
    A gallery opens on its lead like every other page, and the sentence that used to sit
    under the title is the first sentence of that lead.
    """
    lines = ['<header class="masthead">']
    if kicker:
        lines.append(f'  <p class="kicker">{kicker}</p>')
    lines.extend([f"  <h1>{text(heading)}</h1>", "</header>"])
    return "\n".join(lines)


def _tile(*, link: str, src: str, size: tuple[int, int], alt: str, caption: str) -> list[str]:
    width, height = size
    return [
        '      <figure class="tile">',
        f'        <a href="{attribute(link)}">',
        f'          <img src="{attribute(src)}" width="{width}" height="{height}" '
        f'alt="{attribute(alt)}" loading="lazy">',
        "        </a>",
        f"        <figcaption>{caption}</figcaption>",
        "      </figure>",
    ]


def _grid(tiles: list[list[str]]) -> str:
    lines = ['  <section class="images">', '    <div class="grid">']
    for tile in tiles:
        lines.extend(tile)
    lines.extend(["    </div>", "  </section>"])
    return "\n".join(lines)


def _count(images: int) -> str:
    return "1 image" if images == 1 else f"{images} images"


def gallery_page(gallery: Gallery, sections: list[sections_module.Section]) -> str:
    """The HTML for one gallery."""
    page = gallery_page_path(gallery)
    css = relative_href(page, SITE_ROOT / "assets" / "css" / "site.css")

    header = _masthead(f'<a href="{index_path()}">Wallpaper packs</a>', gallery.title)

    intro = ['  <section class="intro">', f"    <p>{text(gallery.blurb)}</p>"]
    if gallery.note:
        intro.append(f"    <p>{text(gallery.note)}</p>")
    if gallery.release:
        intro.append(
            f'    <p>Full size: <a href="{attribute(gallery.release)}">release downloads</a>.</p>'
        )
    intro.append(f'    <p><a href="{index_path()}">All wallpaper packs</a></p>')
    intro.append("  </section>")

    reopened = links.opened(page)
    tiles = []
    for image in gallery.images:
        web_res = gallery.directory / image.file
        thumb = gallery.thumbs_directory / image.file
        caption = f"<strong>{text(image.title)}</strong> — {text(image.caption)}"
        if image.credit:
            caption += f' <span class="credit">{text(image.credit)}</span>'
        opened = reopened.get(f"gallery:{gallery.slug}/{image.file}")
        if opened:
            caption += f' <a class="open" href="{attribute(opened)}">{figures.OPEN_TEXT}</a>'
        tiles.append(
            _tile(
                link=relative_href(page, web_res),
                src=relative_href(page, thumb),
                size=image.thumb_size,
                alt=image.alt,
                caption=caption,
            )
        )

    return _shell(
        page=page,
        title=f"{gallery.title} — Making Fractal Wallpapers",
        css=css,
        bar=topbar(page),
        rail=sections_module.block(page, sections),
        header=header,
        blocks=["\n".join(intro), _grid(tiles)],
    )


def gallery_index(galleries: list[Gallery], sections: list[sections_module.Section]) -> str:
    """The HTML for the Wallpaper packs page: its prose and packs, then a cover tile per
    publishable gallery, of which there are none today."""
    page = GALLERIES_DIR / "index.html"
    css = relative_href(page, SITE_ROOT / "assets" / "css" / "site.css")
    article = relative_href(page, SITE_ROOT / "index.html")

    header = _masthead(None, "Wallpaper packs")

    # The page is its placed master *(packs_page_ckpt153)*: `builder/packs.py` holds the
    # prose and the record, and each marker becomes the block it names. A figure marker is
    # the registry's block, derived here exactly as `check` derives it, because a generated
    # page has no hand to paste a block and `pages` holds the whole file to this function.
    registry = figures.load_all()
    opened = links.opened(page)
    blocks = [
        packs.prose_section(
            page, lambda identifier: figures.markup(registry[identifier], opened), article
        )
    ]
    if galleries:
        tiles = []
        for gallery in galleries:
            cover = gallery.images[0]
            link = f"{gallery.slug}.html"
            caption = (
                f'<strong><a href="{link}">{text(gallery.title)}</a></strong> — '
                f"{text(gallery.blurb)} "
                f'<span class="credit">{_count(len(gallery.images))}</span>'
            )
            tiles.append(
                _tile(
                    link=link,
                    src=relative_href(page, gallery.thumbs_directory / cover.file),
                    size=cover.thumb_size,
                    alt=cover.alt,
                    caption=caption,
                )
            )
        blocks.append(_grid(tiles))

    return _shell(
        page=page,
        title="Wallpaper packs — Making Fractal Wallpapers",
        css=css,
        bar=topbar(page),
        rail=sections_module.block(page, sections),
        header=header,
        blocks=blocks,
    )


def library_page(sections: list[sections_module.Section]) -> str:
    """The palette library, every map as a strip, grouped by the colour it is dominant in.

    Generated rather than written because it is nine hundred rows of the same shape, and
    the shape is a record: `check` re-derives it and compares, so a palette that entered
    the record and not the page is a failing check rather than a gap nobody looks at. The
    record is this repository's own — `palettes/library.jsonl`, the way a gallery has its
    `gallery.jsonl` — so the page derives from committed text here and the checkout next
    door is what the *record* is held to, by the `library` check, where there is one.
    """
    page = palettes_module.library_page_path()
    directory = palettes_module.library_assets_dir()
    width, height = palettes_module.LIBRARY_STRIP
    article = relative_href(page, SITE_ROOT / "article" / "color-palettes.html")
    tools = relative_href(page, sections_module.TOOLS) + "#palettes"
    own = relative_href(page, SITE_ROOT / "palettes" / "make-your-own.html")

    blocks = [
        NEWLINE.join(
            [
                '  <section class="intro">',
                f"    <p>{text(palettes_module.library_lead())}</p>",
                f'    <p>The <a href="{attribute(own)}">palettes I made</a> are free to '
                f'download, under CC0, from <a href="{attribute(tools)}">Tools and data</a>.</p>',
                f'    <p><a href="{attribute(article)}">Back to Color palettes</a></p>',
                "  </section>",
            ]
        )
    ]
    for hue, group in palettes_module.held_hues():
        lines = [
            '  <section class="palette-group">',
            # A parenthesis and not an em-dash: the library page is generated, so
            # `builder/dashes.py` cannot sweep it and the rule is held at the two places
            # that write its words, here and `palettes.LIBRARY_LEAD`.
            f'    <h2 id="hue-{hue}">{text(hue.capitalize())} ({len(group)} palettes)</h2>',
            '    <div class="palette-grid">',
        ]
        for held in group:
            lines.extend(_palette_cell(held, page, directory, width, height))
        lines.extend(["    </div>", "  </section>"])
        blocks.append(NEWLINE.join(lines))

    return _shell(
        page=page,
        title=f"{palettes_module.LIBRARY_TITLE} — {SITE_TITLE}",
        css=relative_href(page, SITE_ROOT / "assets" / "css" / "site.css"),
        bar=topbar(page),
        rail=sections_module.block(page, sections),
        header=_masthead(
            f'<a href="{attribute(article)}">Color palettes</a>', palettes_module.LIBRARY_TITLE
        ),
        blocks=blocks,
    )


def _palette_cell(held, page: Path, directory: Path, width: int, height: int) -> list[str]:
    """One cell of the hue grid: a palette's gradient and the name the explorer shows it
    under, and nothing else *(Matt, tools_figures_ckpt156)*. The library's own id is the
    key a link carries and never a name a reader is shown."""
    return [
        '      <figure class="palette">',
        f"        {_strip(held, page, directory, width, height)}",
        f"        <figcaption>{text(held.display)}</figcaption>",
        "      </figure>",
    ]


def _strip(held, page: Path, directory: Path, width: int, height: int) -> str:
    """One gradient, at the size the library page draws every one of them."""
    source = relative_href(page, directory / held.strip)
    return (
        f'<img src="{attribute(source)}" width="{width}" height="{height}" '
        f'alt="{attribute(held.alt)}" loading="lazy">'
    )


NOT_FOUND = SITE_ROOT / "404.html"


def not_found_page(sections: list[sections_module.Section]) -> str:
    """The page GitHub Pages serves for any address under the site that names nothing.

    Pages answers a missing path at **any depth** with this one file, unredirected, so the
    address bar may read `/fractals/a/b/c` while the page is `404.html` from the root, and
    every relative link it carries would resolve against `a/b/` and break. So this page,
    and only this page, carries a `<base>` naming the served root, `SITE_URL`: the bar, the
    rail, the stylesheet, the icons and the two links below are all spelled exactly as they
    are on any root page — relative, from `relative_href` — and resolve against the root
    wherever the reader landed. One absolute URL, rather than every link on the page made
    absolute by hand. The cost is that the page opened from disk or from `serve` draws its
    stylesheet from production, which is where it is the only page anyone sees.

    No masthead and no heading: the words are the whole of the page, exactly as
    release_polish_ckpt157 gives them, and the rail is the way back into the article the
    way it is on a gallery page.
    """
    page = NOT_FOUND
    home = relative_href(page, SITE_ROOT / index_path())
    start = relative_href(page, sections_module.START)
    return _shell(
        page=page,
        title=f"Page not found — {SITE_TITLE}",
        css=relative_href(page, SITE_ROOT / "assets" / "css" / "site.css"),
        bar=topbar(page),
        rail=sections_module.block(page, sections),
        header="",
        blocks=[
            NEWLINE.join(
                [
                    '  <section class="prose">',
                    f"    <p>That page isn't here. Try the "
                    f'<a href="{attribute(home)}">home page</a> or '
                    f'<a href="{attribute(start)}">Start here</a>.</p>',
                    "  </section>",
                ]
            )
        ],
        base=SITE_URL,
    )


def generated_pages(galleries: list[Gallery], sections: list[sections_module.Section]) -> dict:
    """Every page the builder owns, as {path: html}. The set `check` compares against.

    The galleries handed in are the **publishable** ones — `galleries.load_all()`, which a
    staged gallery is deliberately not in. A staged record is a record and its pictures
    with no page made from them, so there is nothing for this module to write and nothing
    for the index to carry a cover tile of.
    """
    pages = {GALLERIES_DIR / "index.html": gallery_index(galleries, sections)}
    for gallery in galleries:
        pages[gallery_page_path(gallery)] = gallery_page(gallery, sections)
    pages[palettes_module.library_page_path()] = library_page(sections)
    pages[NOT_FOUND] = not_found_page(sections)
    return pages
