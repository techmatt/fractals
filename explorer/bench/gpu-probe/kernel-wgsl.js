// The per-pixel loop in WGSL for the probe, in both arithmetics: the double-single kernel
// is the Deep tab's own, `explorer/deep-gpu-wgsl.js` (`model_ds.rs`, here with the
// interior switch compiled out, which is how stage 2's bundles were written), so the probe
// and the explorer run one kernel text; the `f32` kernel (`model.rs` on the `F32Pair`
// orbit, no proof, no skip) is the probe's alone and is built here on the same uniforms,
// bindings, helpers and entry points.
//
// Both carry Phase 2's two edits, so that they keep agreeing with the model bit for bit
// where a stored zero meets a deep delta: the reconstruct and the rebase test read
// `reads_scaled` (`ez == -127 ||` beside the gate), and the careful step's unit is
// `careful_unit`.
//
// A GPU that flushes subnormals (D3D12 does) can still leave the double-single kernel's
// `d_lo` an ulp or two from the model's, which keeps them: near the quick path's `2^-76`
// gate an error term falls below `2^-126` (`model_ds.rs`, on the gate). That moves
// nothing above the pair's rounding, but it is a difference in bits, which the probe
// counts by comparing every word of the state rather than `n` alone; `deep-gpu-model`'s
// `export --ftz-check on` predicts which pixels.

